const { Client } = require('pg');

const SQL = `
create table if not exists name_history (
  id bigint generated by default as identity primary key,
  user_requirement text not null,
  name_result text not null,
  model_name text not null,
  created_at timestamp with time zone default now()
);

alter table name_history enable row level security;

drop policy if exists "name_history_read" on name_history;
create policy "name_history_read" on name_history for select using (true);

drop policy if exists "name_history_insert" on name_history;
create policy "name_history_insert" on name_history for insert with check (true);
`;

(async () => {
  const client = new Client({
    host: process.env.PGHOST,
    port: Number(process.env.PGPORT || 6543),
    user: process.env.PGUSER,
    password: process.env.PGPASSWORD,
    database: 'postgres',
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: 20000,
  });
  await client.connect();
  console.log('connected');
  await client.query(SQL);
  const { rows } = await client.query(
    "select relname, relrowsecurity from pg_class where relname='name_history'"
  );
  console.log('table:', rows);
  const pol = await client.query("select policyname, cmd from pg_policies where tablename='name_history'");
  console.log('policies:', pol.rows);
  await client.end();
})().catch((e) => {
  console.error('ERR', e.message);
  process.exit(1);
});
